/*
 * pdm_infer.h  -  motor-fault inference from one window of armature current.
 *
 * Plain C++11, no STL, no heap, no exceptions. Single precision only
 * (the ESP32 has a hardware FPU for float, not for double).
 *
 * Usage:
 *     #include "pdm_infer.h"
 *     pdm_init();                                   // once, at startup
 *     ... fill pdm_re[0..PDM_N-1] with current samples in AMPS at 10 kHz ...
 *     int cls = pdm_classify(nullptr);              // 1 healthy, 2 electrical, 3 mechanical
 *
 * NOTE: pdm_classify() uses pdm_re / pdm_im as FFT workspace, so the sample
 * buffer is overwritten. Refill it before the next call.
 *
 * RAM:  pdm_re + pdm_im + twiddle table = 3 * 16 KB = 48 KB static.
 * Flash: the generated model in pdm_model.h (a few tens of KB at most).
 */
#ifndef PDM_INFER_H
#define PDM_INFER_H

#include <stdint.h>
#include <math.h>
#include "pdm_model.h"      /* generated by train_export.py */

#ifndef PDM_N
#error "pdm_model.h must define PDM_N"
#endif

float pdm_re[PDM_N];        /* sample buffer, then FFT real part   */
float pdm_im[PDM_N];        /* FFT imaginary part                  */
static float pdm_tc[PDM_N / 2];   /* cos(2*pi*k/N), k < N/2        */
static float pdm_ts[PDM_N / 2];   /* sin(2*pi*k/N), k < N/2        */

static inline void pdm_init(void) {
    for (uint32_t k = 0; k < PDM_N / 2; k++) {
        const double a = 6.283185307179586476925286766559 * (double)k / (double)PDM_N;
        pdm_tc[k] = (float)cos(a);
        pdm_ts[k] = (float)sin(a);
    }
}

/* cos(2*pi*n/N) for n in [0, N), using the half-size table */
static inline float pdm_cosn(uint32_t n) {
    if (n < PDM_N / 2) return pdm_tc[n];
    if (n == PDM_N / 2) return -1.0f;
    return pdm_tc[PDM_N - n];
}

/* in-place iterative radix-2 FFT of pdm_re/pdm_im */
static void pdm_fft(void) {
    for (uint32_t i = 1, j = 0; i < PDM_N; i++) {          /* bit reversal */
        uint32_t bit = PDM_N >> 1;
        for (; j & bit; bit >>= 1) j ^= bit;
        j ^= bit;
        if (i < j) {
            float t = pdm_re[i]; pdm_re[i] = pdm_re[j]; pdm_re[j] = t;
            t = pdm_im[i]; pdm_im[i] = pdm_im[j]; pdm_im[j] = t;
        }
    }
    for (uint32_t len = 2; len <= PDM_N; len <<= 1) {
        const uint32_t half = len >> 1, step = PDM_N / len;
        for (uint32_t i = 0; i < PDM_N; i += len) {
            for (uint32_t k = 0; k < half; k++) {
                const float wr = pdm_tc[k * step];
                const float wi = -pdm_ts[k * step];
                const uint32_t u = i + k, v = u + half;
                const float xr = pdm_re[v] * wr - pdm_im[v] * wi;
                const float xi = pdm_re[v] * wi + pdm_im[v] * wr;
                pdm_re[v] = pdm_re[u] - xr;  pdm_im[v] = pdm_im[u] - xi;
                pdm_re[u] += xr;             pdm_im[u] += xi;
            }
        }
    }
}

/* Feature vector (PDM_NFEAT floats):
 *   [0]            mean current [A]
 *   [1 .. NBANDS]  spectral energy per band (sum of amplitude^2) with the
 *                  white-noise floor subtracted and clipped at 0
 *   [NBANDS+1]     peak amplitude above the noise floor in the peak-search band [A]
 * Spectrum = Hann-windowed (periodic), mean-removed window, amplitude = 2|X|/N.
 * The noise floor is the mean bin power in the floor band, so the features do not
 * change when the current sensor is noisier.
 */
static inline float pdm_a2(int k, float sc) {
    return (pdm_re[k] * pdm_re[k] + pdm_im[k] * pdm_im[k]) * sc * sc;
}

static void pdm_features(float *f) {
    float sum = 0.0f;
    for (uint32_t n = 0; n < PDM_N; n++) sum += pdm_re[n];
    const float mean = sum / (float)PDM_N;

    for (uint32_t n = 0; n < PDM_N; n++) {
        const float w = 0.5f - 0.5f * pdm_cosn(n);
        pdm_re[n] = (pdm_re[n] - mean) * w;
        pdm_im[n] = 0.0f;
    }
    pdm_fft();

    const float sc = 2.0f / (float)PDM_N;
    float fl = 0.0f;
    for (int k = PDM_FLOOR_LO; k < PDM_FLOOR_HI; k++) fl += pdm_a2(k, sc);
    fl /= (float)(PDM_FLOOR_HI - PDM_FLOOR_LO);

    f[0] = mean;
    for (int b = 0; b < PDM_NBANDS; b++) {
        float e = 0.0f;
        for (int k = PDM_BAND_LO[b]; k < PDM_BAND_HI[b]; k++) e += pdm_a2(k, sc);
        e -= (float)(PDM_BAND_HI[b] - PDM_BAND_LO[b]) * fl;
        f[1 + b] = (e > 0.0f) ? e : 0.0f;
    }
    float pk2 = 0.0f;
    for (int k = PDM_PEAK_LO; k < PDM_PEAK_HI; k++) {
        const float a2 = pdm_a2(k, sc);
        if (a2 > pk2) pk2 = a2;
    }
    pk2 -= fl;
    f[1 + PDM_NBANDS] = (pk2 > 0.0f) ? sqrtf(pk2) : 0.0f;
}

/* Random-forest soft vote over the generated flat tree arrays.
 * Returns the class label (1..PDM_NCLASS). */
static int pdm_predict(const float *f) {
    float acc[PDM_NCLASS];
    for (int c = 0; c < PDM_NCLASS; c++) acc[c] = 0.0f;
    for (int t = 0; t < PDM_NTREES; t++) {
        int node = PDM_ROOT[t];
        while (PDM_FEAT[node] >= 0)
            node = (f[PDM_FEAT[node]] <= PDM_THR[node]) ? PDM_LEFT[node] : PDM_RIGHT[node];
        const int leaf = PDM_LEFT[node];                    /* leaf index */
        for (int c = 0; c < PDM_NCLASS; c++) acc[c] += PDM_LEAF[leaf * PDM_NCLASS + c];
    }
    int best = 0;
    for (int c = 1; c < PDM_NCLASS; c++) if (acc[c] > acc[best]) best = c;
    return best + 1;
}

/* Full pipeline on the samples currently in pdm_re[]. feat_out may be null. */
static int pdm_classify(float *feat_out) {
    float f[PDM_NFEAT];
    pdm_features(f);
    if (feat_out) for (int i = 0; i < PDM_NFEAT; i++) feat_out[i] = f[i];
    return pdm_predict(f);
}

#endif /* PDM_INFER_H */
